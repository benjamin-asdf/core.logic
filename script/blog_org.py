"""Converts the blog series in docs/blog/ to org posts for
benjamin-schwerdtner.de (the faster-than-light-memes repo).

Usage: python3 script/blog_org.py SITE_POSTS_DIR

Writes the English versions only; the German versions are translations of
these, kept next to them as <base>_de."""
import re, subprocess, sys
from pathlib import Path

REPO = 'https://github.com/benjamin-asdf/core.logic'
DATE = '2026-10-28 Wed'
TAGS = ['clojure', 'logic', 'programming', 'public']
# identifiers of the posts in atom.xml and Planet Clojure (the :feed: tag)
FEED = {'20261028T100000'}

# source file, identifier of the English version (German is +1), base name
POSTS = [
    ('README.md', '20261028T100000', 'my-core-logic-fork'),
    ('01-relational-maps.md', '20261028T100002', 'core-logic-fork-1-relational-maps'),
    ('02-no-unsupported-behaviour.md', '20261028T100004', 'core-logic-fork-2-no-unsupported-behaviour'),
    ('03-making-it-fast.md', '20261028T100006', 'core-logic-fork-3-making-it-fast'),
    ('04-vectors.md', '20261028T100008', 'core-logic-fork-4-vectors'),
    ('05-literature-and-parity.md', '20261028T100010', 'core-logic-fork-5-literature-and-parity'),
    ('06-relational-hdc.md', '20261028T100012', 'core-logic-fork-6-relational-hdc'),
    ('07-sets.md', '20261028T100014', 'core-logic-fork-7-sets'),
    ('08-side-by-side-with-minikanren.md', '20261028T100016', 'core-logic-fork-8-side-by-side-with-minikanren'),
    ('09-a-relational-clojure-interpreter.md', '20261028T100018', 'core-logic-fork-9-a-relational-clojure-interpreter'),
]

FOOTER = '\n-----\n\n/Generated by Claude on Benjamin Schwerdtner\'s behalf./\n'


def link_target(target):
    """The org link target for a markdown link target, or None to keep it."""
    path = target.split('#')[0]
    for src, ident, _ in POSTS:
        if path == src:
            return f'denote:{ident}'
    if path == '../../README.md':
        return f'{REPO}#readme'
    if path.startswith('../'):
        return f'{REPO}/blob/master/docs/{path[3:]}'
    return None


def org_body(md):
    org = subprocess.run(['pandoc', '-f', 'gfm', '-t', 'org', '--wrap=preserve'],
                         input=md, capture_output=True, text=True, check=True).stdout
    org = re.sub(r':PROPERTIES:\n(?::[A-Z_]+:.*\n)*?:END:\n', '', org)
    title = re.match(r'\* (.*)\n', org).group(1)
    org = org[org.index('\n') + 1:]
    org = re.sub(r'^\*(\*+) ', r'\1 ', org, flags=re.M)

    def relink(m):
        t = link_target(m.group(1).removeprefix('file:'))
        return f'[[{t}]' if t else m.group(0)
    org = re.sub(r'\[\[([^\]]+)\]', relink, org)
    return title, org.strip() + '\n'


def inline_codes():
    """The inline code spans of all posts."""
    return {c for src, _, _ in POSTS
            for c in re.findall(r'`([^`\n]+)`', Path('docs/blog', src).read_text())}


def fix_verbatim(org, codes):
    """Org's =verbatim= ends at the first = followed by a space or
    punctuation, so code containing = is written as ~code~ instead."""
    for c in sorted(codes, key=len, reverse=True):
        if '=' in c and '~' not in c:
            org = org.replace(f'={c}=', f'~{c}~')

    # in a table, a | inside code would split the cell: write it as HTML
    def html_code(m):
        c = m.group(1).replace('&', '&amp;').replace('<', '&lt;').replace('|', '&#124;')
        return f'@@html:<code>{c}</code>@@'
    piped = [c.replace('\\|', '|') for c in codes if '\\|' in c]

    # =a=/=b=: org ends no verbatim before a /, so write the pair as HTML
    def html_pair(m):
        return '@@html:' + '/'.join(html_code(re.match(r'(.*)', c))[7:-2]
                                    for c in m.groups()) + '@@'
    org = re.sub(r'=([^=\s]+)=/=([^=\s]+)=', html_pair, org)

    def fix_row(row):
        row = row.group(0)
        for c in piped:
            row = row.replace(f'={c}=', html_code(re.match(r'(.*)', c)))
        return row
    return re.sub(r'^\|.*$', fix_row, org, flags=re.M)


def main(out_dir):
    codes = inline_codes()
    # the German versions are translations with the same inline code
    for f in Path(out_dir).glob('20261028T1000*_de__*.org'):
        f.write_text(fix_verbatim(f.read_text(), codes))
    for src, ident, base in POSTS:
        title, body = org_body(Path('docs/blog', src).read_text())
        body = fix_verbatim(body, codes)
        head = (f'#+title:      {title}\n'
                f'#+date:       [{DATE}]\n'
                f'#+filetags:   :{":".join(TAGS + (["feed"] if ident in FEED else []))}:\n'
                f'#+identifier: {ident}\n'
                f'#+LANGUAGE: en\n'
                f'#+OPTIONS: toc:nil\n'
                f'#+EXPORT_FILE_NAME: {base}_en\n\n')
        name = f'{ident}--{base}_en__{"_".join(TAGS)}.org'
        Path(out_dir, name).write_text(head + body + FOOTER)
        print(name)


if __name__ == '__main__':
    main(sys.argv[1])

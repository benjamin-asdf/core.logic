(ns clojure.core.logic.fmk-support
  "Compares core.logic answers with faster-miniKanren's printed answers, for
   the tests generated by script/fmk_tests.py."
  (:refer-clojure :exclude [==])
  (:use [clojure.core.logic :only [lcons lcons?]]
        [clojure.core.logic.protocols :only [lfirst lnext]]
        [clojure.test :only [is]])
  (:require [clojure.string :as string]
            [clojure.walk :as walk]))

(defn show
  "Prints a reified term as faster-miniKanren does: pairs with a dot, and
   vars as _.n."
  [x]
  (cond
    (lcons? x) (loop [x x out []]
                 (cond
                   (lcons? x) (recur (lnext x) (conj out (show (lfirst x))))
                   (or (seq? x) (vector? x)) (str "(" (string/join " " (concat out (map show x))) ")")
                   :else (str "(" (string/join " " out) " . " (show x) ")")))
    (or (seq? x) (vector? x)) (str "(" (string/join " " (map show x)) ")")
    (symbol? x) (let [n (name x)]
                  (if (re-matches #"_\d+" n) (str "_." (subs n 1)) n))
    :else (pr-str x)))

(defn- atoms
  "A residual constraint as faster-miniKanren's atomic constraints."
  [c]
  (let [[k & args] c]
    (case (name k)
      "!=" [(into ["=/="] (sort-by str (map (fn [[u v]] (vec (sort [(show u) (show v)]))) args)))]
      "symbolo" [["sym" (show (first args))]]
      "numbero" [["num" (show (first args))]]
      "stringo" [["str" (show (first args))]]
      "absento" [["absento" (show (first args)) (show (second args))]]
      [["other" (pr-str c)]])))

(defn canon [a]
  (if (and (seq? a) (= :- (second a)))
    {:v (show (first a)) :cs (vec (mapcat atoms (drop 2 a)))}
    {:v (show a) :cs []}))

(defn- rename
  "Renames the vars of an answer by first appearance, in the value first,
   then in the constraints, so that two systems' names compare."
  [{:keys [v cs]}]
  (let [names (atom {})
        sub (fn [s]
              (string/replace s #"_\.\d+"
                              (fn [m]
                                (or (@names m)
                                    (let [n (str "_." (count @names))]
                                      (swap! names assoc m n)
                                      n)))))
        v (sub v)
        blank (fn [a] (pr-str (walk/postwalk
                               #(if (string? %)
                                  (string/replace % #"_\.\d+" (fn [m] (get @names m "_")))
                                  %)
                               a)))
        cs (mapv (fn [a] (walk/postwalk #(if (string? %) (sub %) %) a))
                 (sort-by blank cs))
        norm (fn [a]
               (if (= "=/=" (first a))
                 (into ["=/="] (sort (map (comp vec sort) (rest a))))
                 a))]
    [v (sort (map (comp pr-str norm) cs))]))

(defn check
  "Checks core.logic's answers against faster-miniKanren's."
  [title answers expected & {:keys [unordered]}]
  (let [got (map (comp rename canon) answers)
        exp (map rename expected)]
    (is (= (if unordered (sort got) got)
           (if unordered (sort exp) exp))
        title)))

(defn build-num [n]
  (cond
    (odd? n) (lcons 1 (build-num (quot (- n 1) 2)))
    (and (not (zero? n)) (even? n)) (lcons 0 (build-num (quot n 2)))
    (zero? n) '()))
